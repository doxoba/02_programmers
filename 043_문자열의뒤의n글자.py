# -----------------------------------------------

# -----------------------------------------------
# ❓ 질문 2 : 뒤의 n글자를 어떻게 잘라내?
# 😵 페인포인트 : [-n] 으로 쓰면 한 글자만 나오는 줄 몰랐음
# 💡 풀이 : [-n:] 으로 써야 뒤에서 n번째부터 끝까지 전부 가져옴
#           "ProgrammerS123"[-11:]  →  "grammerS123"
# ✅ 팁 : [-n]  → 뒤에서 n번째 글자 하나
#         [-n:] → 뒤에서 n번째부터 끝까지 전부
# -----------------------------------------------

# -----------------------------------------------
# ❓ 질문 3 : 문자열에 append 쓰면 안 되나?
# 😵 페인포인트 : answer = '' 로 만들어놓고 append() 를 써버림
# 💡 풀이 : append()는 리스트 전용!
#           문자열에 담을 때는 그냥 = 로 바로 넣기
#           answer = []  → append 가능
#           answer = ''  → = 또는 += 으로 담기
# ✅ 팁 : 출력이 문자열이면 = '' / 출력이 리스트면 = []
# -----------------------------------------------

# -----------------------------------------------
# 📝 최종 풀이 : 043 문자열의 뒤의 n글자
# -----------------------------------------------
def solution(my_string, n):
    answer = my_string[-n:]
    return answer

