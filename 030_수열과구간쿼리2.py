#    1. queries를 for문으로 하나씩 꺼내서 s, e, k로 이름 붙이기
#    2. range(s, e+1)로 arr의 인덱스 s~e 순회
#    3. arr[j] > k 인 값들만 temp(임시 바구니)에 모으기
#    4. temp가 비어있으면 -1, 아니면 min(temp) → answer에 추가
# ✅ 팁 :
#    - s, e, k = i  →  i[0], i[1], i[2] 한 줄 축약 가능
#    - temp = []는 반드시 for i 루프 안에서 초기화 (query마다 새로 시작)
#    - if temp == [] 는 for j 루프 밖에서 확인 (다 모은 뒤에 판단)
#    - min()은 다 모아놓고 나서 쓰는 것 (모으는 중간 X)
