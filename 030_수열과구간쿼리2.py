# 문제:
# 정수 배열 `arr`와 2차원 정수 배열 `queries`이 주어집니다. `queries`의 원소는 각각 하나의 `query`를 나타내며, `[s, e, k]` 꼴입니다.
# 각 `query`마다 순서대로 `s` ≤ `i` ≤ `e`인 모든 `i`에 대해 `k`보다 크면서 가장 작은 `arr[i]`를 찾습니다.
# 각 쿼리의 순서에 맞게 답을 저장한 배열을 반환하는 solution 함수를 완성해 주세요.
# 단, 특정 쿼리의 답이 존재하지 않으면 -1을 저장합니다.
# ----------------------------------------
# [제한사항]
# - 1 ≤ `arr`의 길이 ≤ 1,000
#   0 ≤ `arr`의 원소 ≤ 1,000,000
# - 1 ≤ `queries`의 길이 ≤ 1,000
#  0 ≤ `s` ≤ `e` < `arr`의 길이
#  0 ≤ `k` ≤ 1,000,000
# ----------------------------------------
# [입출력 예]
# arr | queries | result
# [0, 1, 2, 4, 3] | [[0, 4, 2],[0, 3, 2],[0, 2, 2]] | [3, 4, -1]
# ----------------------------------------
# [입출력 예 설명]
# 입출력 예 #1
# - 첫 번째 쿼리의 범위에는 0, 1, 2, 4, 3이 있으며 이 중 2보다 크면서 가장 작은 값은 3입니다.
# - 두 번째 쿼리의 범위에는 0, 1, 2, 4가 있으며 이 중 2보다 크면서 가장 작은 값은 4입니다.
# - 세 번째 쿼리의 범위에는 0, 1, 2가 있으며 여기에는 2보다 큰 값이 없습니다.
# - 따라서 [3, 4, -1]을 return 합니다.
# ---------------------------------------------------------
# (여기에 내 풀이)

# "arr에서 인덱스가 s~e 사이인 것들만 보고, 그 중 k보다 큰 것들만 골라서, 그 중 최솟값" / 반복문 + 조건문 + 리스트
# queries의 역할 → "arr에서 어디를 어떻게 볼지" 알려주는 명령서
# arr의 역할 → 실제로 값이 들어있는 진열대
def solution(arr, queries):
    answer = []
    for i in queries:   #queries의 i는 [s, e, k] 꼴이니까 
        s = i[0]
        e = i[1]
        k = i[2]
        temp = []
        for j in(range(s, e+1)):
            if arr[j] > k:
                temp.append(arr[j])
        if temp == []:
            answer.append(-1)
        else:
            answer.append(min(temp))
    return answer




# 입력: arr, queries
# 출력: 저장된 answer return
# 규칙: s와 같거나 크고 e와 같거나 작은 인덱스 i 중, k보다 크면서 가장 작은 arr[i]를 찾아 answer 바구니에 넣으면서 반복문 돌리기

