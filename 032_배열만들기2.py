# 문제:
# 정수 `l`과 `r`이 주어졌을 때, `l` 이상 `r`이하의 정수 중에서 숫자 "0"과 "5"로만 이루어진 모든 정수를 오름차순으로 저장한 배열을 return 하는 solution 함수를 완성해 주세요.
# 만약 그러한 정수가 없다면, -1이 담긴 배열을 return 합니다.
# ----------------------------------------
# [제한사항]
# - 1 ≤ `l` ≤ `r` ≤ 1,000,000
# ----------------------------------------
# [입출력 예]
# l | r | result
# 5 | 555 | [5, 50, 55, 500, 505, 550, 555]
# 10 | 20 | [-1]
# ----------------------------------------
# [입출력 예 설명]
# 입출력 예 #1
# - 5 이상 555 이하의 0과 5로만 이루어진 정수는 작은 수부터 5, 50, 55, 500, 505, 550, 555가 있습니다. 따라서 [5, 50, 55, 500, 505, 550, 555]를 return 합니다.
# 입출력 예 #2
# - 10 이상 20 이하이면서 0과 5로만 이루어진 정수는 없습니다. 따라서 [-1]을 return 합니다.
# ---------------------------------------------------------
# (여기에 내 풀이)

def solution(l, r): 
    answer = []  # 바구니
# l부터 r까지 숫자를 하나씩 꺼내서
    for num in range(l,r+1):
# 일단 합격이라고 가정
        합격 = True
# 그 숫자의 각 자리를 보다가
        for i in str(num):
# 0도 아니고 5도 아닌 자리가 나오면
            if i != '0' and i != '5':
# 불합격으로 바꿈
                합격 = False
# 다 봤는데 합격이면 -> 리스트에 추가
        if 합격 == True:
            answer.append(num)
# 다 끝났는데 리스트가 비어있으면 -> [-1] 반환
    if answer == []:
            answer.append(-1)
    return answer

print(solution(5, 555))

# 입력: l , r
# 출력: 배열
# 풀이: if l <= (정수) <= r 중 0과 5로만 이루어진 정수는 오름차순으로 저장, else 배열에 -1 추가



