# 문제:
# 정수 `a`와 `b`가 주어집니다. 각 수를 입력받아 입출력 예와 같은 형식으로 출력하는 코드를 작성해 보세요.
# ----------------------------------------
# [제한사항]
# - -100,000 ≤ `a`, `b` ≤ 100,000
# ----------------------------------------
# [입출력 예]
# 입력 #1
#     4 5
# 출력 #1
#     a = 4
#     b = 5
# ---------------------------------------------------------
# (여기에 내 풀이)
a, b = input().split()
a = int(a)
b = int(b)
print(f"""a = {a}
b = {b}""")

