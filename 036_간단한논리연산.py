# 문제:
# boolean 변수 `x1`, `x2`, `x3`, `x4`가 매개변수로 주어질 때, 다음의 식의 true/false를 return 하는 solution 함수를 작성해 주세요.
# - (`x1` ∨ `x2`) ∧ (`x3` ∨ `x4`)
# ----------------------------------------
# [입출력 예]
# x1 | x2 | x3 | x4 | result
# false | true | true | true | true
# true | false | false | false | false
# ----------------------------------------
# [입출력 예 설명]
# 입출력 예 #1
# - 예제 1번의 `x1`, `x2`, `x3`, `x4`로 식을 계산하면 다음과 같습니다.
#(`x1` ∨ `x2`) ∧ (`x3` ∨ `x4`) ≡ (F ∨ T) ∧ (T ∨ T) ≡ T ∧ T ≡ T
#따라서 true를 return 합니다.
# 입출력 예 #2
# - 예제 2번의 `x1`, `x2`, `x3`, `x4`로 식을 계산하면 다음과 같습니다.
#(`x1` ∨ `x2`) ∧ (`x3` ∨ `x4`) ≡ (T ∨ F) ∧ (F ∨ F) ≡ T ∧ F ≡ F
#따라서 false를 return 합니다.
# ----------------------------------------
# - ∨과 ∧의 진리표는 다음과 같습니다.
# x | y | x ∨ y | x ∧ y
# T | T | T | T
# T | F | T | F
# F | T | T | F
#  | F | F | F
# ---------------------------------------------------------
# (여기에 내 풀이)
# 입력: x1, x2, x3, x4
# 출력: True or False
# 어떻게? 몰라..


# boolean 변수 `x1`, `x2`, `x3`, `x4`가 매개변수로 주어질 때, 다음의 식의 true/false를 return 하는 solution 함수를 작성해 주세요.
# (`x1` ∨ `x2`) ∧ (`x3` ∨ `x4`)
def solution(x1, x2, x3, x4):
    return ( x1 or x2 ) and (x3 or x4)


# 메모:
# -----------------------------------------------
# ❓ 질문 36 : 간단한 논리 연산 (∨, ∧ 기호 해석 + or/and 적용)
# 😵 페인포인트 : ∨ ∧ 기호가 생소했고, 매개변수(파라미터)로
#               값이 자동으로 들어온다는 개념이 낯설었음
# 💡 풀이 : ∨ → or / ∧ → and 로 바꿔서 그대로 return
